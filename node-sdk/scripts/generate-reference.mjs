import ts from 'typescript';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, unlinkSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const sdkRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const prefix = 'typescript-sdk-reference';
const marker = '{/* Generated by node-sdk/scripts/generate-reference.mjs. Do not edit. */}';
const slugs = { NotteClient: 'client', NotteFunction: 'function', NotteVault: 'vault', NottePersona: 'persona', SessionFiles: 'files' };
const slug = name => slugs[name] ?? name.toLowerCase();
const memberSlug = name => name.toLowerCase().replace(/[^a-z0-9_-]+/g, '-').replace(/^-|-$/g, '');
const portableType = text => text.replace(/import\("[^"]+"\)\./g, '');
const fence = text => `\`\`\`typescript\n${text}\n\`\`\``;
// JSDoc is prose, not JSX. Preserve code spans but escape MDX expressions/tags.
const prose = text => text.split(/(`[^`]*`)/g).map(part => part.startsWith('`') ? part : part.replace(/[<>{}]/g, c => ({ '<': '&lt;', '>': '&gt;', '{': '&#123;', '}': '&#125;' })[c])).join('');
const attr = value => JSON.stringify(String(value));

export function createReference(root = sdkRoot) {
  const configPath = resolve(root, 'tsconfig.json');
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  const program = ts.createProgram([resolve(root, 'src/index.ts')], parsed.options);
  const diagnostics = [...parsed.errors, ...ts.getPreEmitDiagnostics(program)];
  if (diagnostics.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: p => p, getCurrentDirectory: () => root, getNewLine: () => '\n',
  }));
  const checker = program.getTypeChecker();
  const entry = program.getSourceFile(resolve(root, 'src/index.ts'));
  const exports = checker.getExportsOfModule(checker.getSymbolAtLocation(entry));
  const unalias = symbol => symbol?.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const local = node => node && relative(resolve(root, 'src'), node.getSourceFile().fileName).split(/[\\/]/)[0] !== '..';
  const modelType = node => {
    if (!local(node)) return false;
    const path = relative(resolve(root, 'src'), node.getSourceFile().fileName).replaceAll('\\', '/');
    // OpenAPI request/response models are useful here; transport internals are not.
    return !path.includes('/') || path === 'lib/client/types.gen.ts';
  };
  const isInternal = node => ts.getJSDocTags(node).some(tag => tag.tagName.text === 'internal');
  const visible = node => !isInternal(node) && !node.name?.getText().startsWith('#') &&
    !node.modifiers?.some(m => m.kind === ts.SyntaxKind.PrivateKeyword || m.kind === ts.SyntaxKind.ProtectedKeyword);
  const doc = symbol => prose(ts.displayPartsToString(symbol?.getDocumentationComment(checker)));
  const typeText = type => portableType(checker.typeToString(type, undefined, ts.TypeFormatFlags.NoTruncation));
  const sourceLink = node => {
    const file = `node-sdk/${relative(root, node.getSourceFile().fileName).replaceAll('\\', '/')}`;
    const line = node.getSourceFile().getLineAndCharacterOfPosition(node.getStart()).line + 1;
    return `[Source: ${file}](https://github.com/nottelabs/notte/blob/main/${file}#L${line})`;
  };
  const page = (title, node, content) => `---\ntitle: ${attr(title)}\n---\nimport AgentMdNotice from '/partials/agent-md-notice.mdx';\n\n<AgentMdNotice />\n\n${marker}\n\n${node ? `${sourceLink(node)}\n\n` : ''}${content.trim()}\n`.replace(/ +$/gm, '');
  const classes = [];
  const types = new Map();
  const publicSymbols = new Set(exports.map(unalias));
  for (const symbol of publicSymbols) {
    const node = symbol.declarations?.[0];
    if (!local(node) || isInternal(node)) continue;
    // The high-level reference excludes generated HTTP operations and proxy subpaths.
    const path = relative(resolve(root, 'src'), node.getSourceFile().fileName);
    if (path.includes('/') || path.includes('\\')) continue;
    if (ts.isClassDeclaration(node)) classes.push({ symbol, node });
    if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) types.set(symbol.name, node);
  }
  classes.sort((a, b) => a.symbol.name.localeCompare(b.symbol.name, 'en'));
  const collectTypes = node => {
    if (!node) return;
    if (ts.isIdentifier(node)) {
      const symbol = unalias(checker.getSymbolAtLocation(node));
      const declaration = symbol?.declarations?.[0];
      if (modelType(declaration) && !isInternal(declaration) &&
          (ts.isTypeAliasDeclaration(declaration) || ts.isInterfaceDeclaration(declaration))) {
        if (types.has(symbol.name) && types.get(symbol.name) !== declaration) throw new Error(`Ambiguous type name: ${symbol.name}`);
        types.set(symbol.name, declaration);
      }
    }
    ts.forEachChild(node, collectTypes);
  };
  const publicMembers = node => node.members.filter(visible);
  for (const { node } of classes) {
    for (const member of publicMembers(node)) {
      collectTypes(member.type);
      for (const parameter of member.parameters ?? []) collectTypes(parameter.type);
      for (const parameter of member.typeParameters ?? []) collectTypes(parameter);
    }
  }
  // Map iteration visits additions: follow model dependencies without importing/executing SDK code.
  for (const node of types.values()) collectTypes(node);

  const pages = new Map();
  const tags = node => ts.getJSDocTags(node).filter(t => ['deprecated', 'returns', 'throws', 'example'].includes(t.tagName.text))
    .map(t => `**${t.tagName.text}:**\n\n${t.tagName.text === 'example' ? fence(ts.getTextOfJSDocComment(t.comment) ?? '') : prose(ts.getTextOfJSDocComment(t.comment) ?? '')}`).join('\n\n');
  const signatures = (name, nodes) => nodes.map(node => {
    const signature = checker.getSignatureFromDeclaration(node);
    const modifiers = node.modifiers?.some(m => m.kind === ts.SyntaxKind.StaticKeyword) ? 'static ' : '';
    return `${modifiers}${name}${portableType(checker.signatureToString(signature, node, ts.TypeFormatFlags.NoTruncation))};`;
  }).join('\n');
  const params = node => (node.parameters ?? []).map(p => {
    const symbol = checker.getSymbolAtLocation(p.name);
    const type = p.type?.getText() ?? typeText(checker.getTypeAtLocation(p));
    const required = !p.questionToken && !p.initializer && !p.dotDotDotToken;
    const details = [doc(symbol), p.initializer ? `Default:\n\n${fence(p.initializer.getText())}` : ''].filter(Boolean).join('\n\n');
    return `<ParamField body=${attr(p.name.getText())} type={${attr(type)}}${required ? ' required' : ''}>\n${details || ' '}\n</ParamField>`;
  }).join('\n\n');
  const related = nodes => {
    const names = new Set();
    const visit = n => {
      if (!n) return;
      if (ts.isIdentifier(n)) {
        const symbol = unalias(checker.getSymbolAtLocation(n));
        if (types.has(symbol?.name)) names.add(symbol.name);
      }
      ts.forEachChild(n, visit);
    };
    nodes.forEach(n => { visit(n.type); (n.parameters ?? []).forEach(p => visit(p.type)); visit(n.heritageClauses?.[0]); });
    return names.size ? `## Related types\n\n${[...names].sort().map(name => `- [${name}](/${prefix}/types/${name.toLowerCase()})`).join('\n')}` : '';
  };
  const groups = [];
  for (const { symbol, node } of classes) {
    const name = symbol.name;
    const classSlug = slug(name);
    const members = publicMembers(node);
    const constructors = members.filter(ts.isConstructorDeclaration);
    const methods = new Map();
    for (const member of members.filter(ts.isMethodDeclaration)) {
      const key = member.name.getText();
      methods.set(key, [...(methods.get(key) ?? []), member]);
    }
    const methodLinks = [];
    const nav = [`${prefix}/manual/${classSlug}`];
    for (const [methodName, declarations] of methods) {
      // Implementations are not overloads and must not broaden the published API.
      const overloads = declarations.some(n => !n.body) ? declarations.filter(n => !n.body) : declarations;
      const method = declarations[0];
      const path = `${prefix}/${classSlug}/${memberSlug(methodName)}`;
      if (pages.has(`${path}.mdx`)) throw new Error(`Duplicate reference path: ${path}`);
      const contents = [doc(checker.getSymbolAtLocation(method.name)), fence(signatures(`${name}.${methodName}`, overloads))];
      for (const [i, overload] of overloads.entries()) {
        if (overload.parameters.length) contents.push(`## Parameters${overloads.length > 1 ? ` (overload ${i + 1})` : ''}\n\n${params(overload)}`);
        const signature = checker.getSignatureFromDeclaration(overload);
        contents.push(`## Returns${overloads.length > 1 ? ` (overload ${i + 1})` : ''}\n\n${fence(typeText(signature.getReturnType()))}`);
      }
      contents.push(tags(method), related(overloads));
      pages.set(`${path}.mdx`, page(`${name}.${methodName}`, method, contents.filter(Boolean).join('\n\n')));
      nav.push(path);
      methodLinks.push(`- [${methodName}](/${path})${doc(checker.getSymbolAtLocation(method.name)) ? `: ${doc(checker.getSymbolAtLocation(method.name)).split('\n')[0]}` : ''}`);
    }
    const props = members.filter(m => ts.isPropertyDeclaration(m) || ts.isGetAccessorDeclaration(m)).map(m => {
      const symbol = checker.getSymbolAtLocation(m.name);
      return `### ${m.name.getText()}\n\n${fence(`${m.name.getText()}${m.questionToken ? '?' : ''}: ${typeText(checker.getTypeAtLocation(m))}`)}\n\n${doc(symbol)}`;
    });
    const ctorOverloads = constructors.some(n => !n.body) ? constructors.filter(n => !n.body) : constructors;
    const contents = [doc(symbol), fence(`import { ${name} } from 'notte-sdk';`), ctorOverloads.length ? `## Constructor\n\n${fence(signatures(`new ${name}`, ctorOverloads))}\n\n${ctorOverloads.map((ctor, i) => `${ctorOverloads.length > 1 ? `### Overload ${i + 1}\n\n` : ''}${params(ctor)}`).join('\n\n')}\n\n${related(ctorOverloads)}` : '', props.length ? `## Properties\n\n${props.join('\n\n')}` : '', methodLinks.length ? `## Methods\n\n${methodLinks.join('\n')}` : ''];
    pages.set(`${prefix}/manual/${classSlug}.mdx`, page(name, node, contents.filter(Boolean).join('\n\n')));
    groups.push({ group: name, collapsed: true, pages: nav });
  }
  for (const [name, node] of [...types].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
    const path = `${prefix}/types/${name.toLowerCase()}`;
    if (pages.has(`${path}.mdx`)) throw new Error(`Duplicate reference path: ${path}`);
    const symbol = checker.getSymbolAtLocation(node.name);
    const type = checker.getTypeAtLocation(node);
    // Resolve inherited/mapped object options as well as showing their source declaration.
    const properties = !type.isUnion() && !(type.flags & ts.TypeFlags.StringLike) ? checker.getPropertiesOfType(type) : [];
    const fields = properties.filter(p => p.declarations?.some(d => local(d) && visible(d))).map(p => {
      const declaration = p.valueDeclaration ?? p.declarations[0];
      const value = typeText(checker.getTypeOfSymbolAtLocation(p, node));
      return `<ParamField body=${attr(p.name)} type={${attr(value)}}${p.flags & ts.SymbolFlags.Optional ? '' : ' required'}>\n${doc(p) || ' '}${tags(declaration) ? `\n\n${tags(declaration)}` : ''}\n</ParamField>`;
    });
    pages.set(`${path}.mdx`, page(name, node, [doc(symbol), fence(node.getText()), tags(node), fields.length ? `## Fields\n\n${fields.join('\n\n')}` : '', related([node])].filter(Boolean).join('\n\n')));
  }
  pages.set(`${prefix}/manual/index.mdx`, page('Node SDK reference', null, `This reference is generated from the public high-level classes, their signatures, JSDoc, and related types in \`node-sdk/src\`. It documents the checked-in SDK source; match it to the version you use.\n\nInstall the SDK:\n\n\`\`\`sh\nnpm install notte-sdk\n\`\`\`\n\n${classes.filter(({ symbol }) => symbol.name !== 'Encryption').map(({ symbol }) => `- [${symbol.name}](/${prefix}/manual/${slug(symbol.name)})`).join('\n')}\n\nThe generated low-level HTTP functions, legacy client helpers, and proxy subpath entrypoints are not part of this high-level reference. See the [API reference](/api-reference/authentication) for HTTP endpoints and the [Python SDK reference](/sdk-reference/manual/index) for Python.\n\nTo update these pages, edit the TypeScript source or its JSDoc and run \`npm run docs:generate --prefix node-sdk\`. CI checks for stale generated pages.`));
  const debugPaths = ['client/getconfig', 'client/getclient', 'session/getresponse']
    .map(path => `${prefix}/${path}`).filter(path => pages.has(`${path}.mdx`));
  const categories = { 'Getting Started': [], 'Core Features': [], Tooling: [], Debug: debugPaths };
  categories['Getting Started'].push(`${prefix}/manual/index`);
  const labels = { NotteClient: 'Client', NotteFunction: 'Function', NotteVault: 'Vault', NottePersona: 'Persona', SessionFiles: 'File Storage' };
  const classOrder = ['NotteClient', 'Session', 'Agent', 'NotteFunction', 'NotteVault', 'NottePersona', 'SessionFiles'];
  for (const group of groups.sort((a, b) => (classOrder.indexOf(a.group) + 1 || 100) - (classOrder.indexOf(b.group) + 1 || 100))) {
    if (group.group === 'Encryption') continue;
    const category = group.group === 'NotteClient' ? 'Getting Started'
      : ['NotteVault', 'NottePersona', 'SessionFiles', 'Encryption'].includes(group.group) ? 'Tooling' : 'Core Features';
    categories[category].push({ ...group, group: labels[group.group] ?? group.group, pages: group.pages.filter(path => !debugPaths.includes(path)) });
  }
  // Use the SDK's action union, not every model with "Action" in its name.
  const actionSpace = types.get('ActionSpace');
  const actions = actionSpace && checker.getTypeAtLocation(actionSpace).getProperty('actions');
  const actionType = actions && checker.getIndexTypeOfType(checker.getTypeOfSymbolAtLocation(actions, actionSpace), ts.IndexKind.Number);
  if (actionType) {
    const paths = (actionType.isUnion() ? actionType.types : [actionType]).map(type => type.aliasSymbol?.name ?? type.getSymbol()?.name)
      .filter(name => types.has(name)).map(name => `${prefix}/types/${name.toLowerCase()}`);
    categories['Core Features'].splice(1, 0, { group: 'Actions', collapsed: true, pages: paths });
  }
  return { pages, navigation: { group: 'Node SDK', pages: Object.entries(categories).filter(([, pages]) => pages.length).map(([group, pages]) => ({ group, pages })) } };
}

// Replace only this navigation group, preserving all unrelated docs.json formatting.
export function replaceNavigation(text, group) {
  const needle = '"group": "Node SDK"';
  const index = text.indexOf(needle);
  if (index < 0 || text.indexOf(needle, index + 1) >= 0) throw new Error('Expected one Node SDK navigation group');
  const start = text.lastIndexOf('{', index);
  let depth = 0, quoted = false, escaped = false;
  for (let end = start; end < text.length; end++) {
    const c = text[end];
    if (quoted) {
      if (escaped) escaped = false;
      else if (c === '\\') escaped = true;
      else if (c === '"') quoted = false;
    } else if (c === '"') quoted = true;
    else if (c === '{') depth++;
    else if (c === '}' && --depth === 0) {
      const indent = text.slice(text.lastIndexOf('\n', start) + 1, start);
      const result = text.slice(0, start) + JSON.stringify(group, null, 2).replaceAll('\n', `\n${indent}`) + text.slice(end + 1);
      JSON.parse(result);
      return result;
    }
  }
  throw new Error('Unclosed Node SDK navigation group');
}

export function syncReference({ pages, navigation }, docsRoot, check = false) {
  const expected = new Map(pages);
  const navPath = resolve(docsRoot, 'docs.json');
  expected.set('docs.json', replaceNavigation(readFileSync(navPath, 'utf8'), navigation));
  const output = resolve(docsRoot, prefix);
  const existing = existsSync(output) ? readdirSync(output, { recursive: true }).filter(p => p.endsWith('.mdx')).map(p => `${prefix}/${p}`) : [];
  const stale = existing.filter(p => !pages.has(p));
  // Never delete or overwrite a manually maintained file in the generated tree.
  for (const name of new Set([...existing, ...pages.keys()])) {
    const path = resolve(docsRoot, name);
    if (existsSync(path) && !readFileSync(path, 'utf8').includes(marker)) throw new Error(`Refusing to overwrite unowned file: ${name}`);
  }
  const changed = [...expected].filter(([name, content]) => !existsSync(resolve(docsRoot, name)) || readFileSync(resolve(docsRoot, name), 'utf8') !== content);
  if (!check) {
    for (const [name, content] of changed) {
      const path = resolve(docsRoot, name);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
    for (const name of stale) unlinkSync(resolve(docsRoot, name));
  }
  return [...changed.map(([name]) => name), ...stale];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const reference = createReference();
  const changed = syncReference(reference, resolve(sdkRoot, '../docs/src'), check);
  if (check && changed.length) {
    console.error(`Stale TypeScript reference. Run npm run docs:generate --prefix node-sdk:\n${changed.join('\n')}`);
    process.exitCode = 1;
  } else console.log(`${reference.pages.size} TypeScript reference pages ${check ? 'verified' : 'generated'}; ${changed.length} changed files.`);
}
