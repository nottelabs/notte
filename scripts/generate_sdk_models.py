#!/usr/bin/env python3
"""Generate SDK-owned Pydantic models without importing core or changing the public API.

Run `make sdk-codegen` to write, or `make sdk-codegen-check` to compare without writing.
The pinned generator owns schema translation; this driver only configures it, checks
coverage, formats output, and compares bytes. It never downloads a schema.
"""

from __future__ import annotations

import argparse
import difflib
import hashlib
import json
import subprocess
import sys
from importlib.metadata import version
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import cast

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "openapi/openapi.json"
OUTPUT = ROOT / "packages/notte-sdk/src/notte_sdk/_generated"
VERSIONS = {"datamodel-code-generator": "0.86.0", "ruff": "0.11.10"}


def render(snapshot: Path = SNAPSHOT) -> dict[str, str]:
    """Render in isolation, so --check never modifies the checkout."""
    for package, expected in VERSIONS.items():
        actual = version(package)
        if actual != expected:
            raise ValueError(f"{package}=={expected} required, found {actual}; run uvx uv@latest sync --all-groups")

    with TemporaryDirectory(prefix="notte-sdk-models-") as directory:
        scratch = Path(directory)
        # Stable basename and no timestamp/absolute source paths in the generated bytes.
        source = scratch / "openapi.json"
        spec = json.loads(snapshot.read_bytes())
        # Inline enums describe string fields; named schema enums retain .value.
        for schema in spec["components"]["schemas"].values():
            if "enum" in schema:
                schema["x-enum-field-as-literal"] = False
        _ = source.write_text(json.dumps(spec))
        output = scratch / "models.py"
        metadata = scratch / "metadata.json"
        _ = subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(source),
                "--input-file-type",
                "openapi",
                "--output",
                str(output),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.11",
                "--output-datetime-class",
                "datetime",
                "--disable-timestamp",
                "--formatters",
                "builtin",
                "--use-annotated",
                "--strict-nullable",
                "--enum-field-as-literal",
                "all",
                "--use-specialized-enum",
                "--capitalise-enum-members",
                "--strict-refs",
                "--no-allow-remote-refs",
                "--openapi-scopes",
                "schemas",
                "paths",
                "parameters",
                "--use-operation-id-as-name",
                "--emit-model-metadata",
                str(metadata),
            ],
            cwd=scratch,
            check=True,
        )
        model_metadata = json.loads(metadata.read_text())
        index: dict[str, str] = {}
        for model in model_metadata["models"]:
            ref = cast(str, model["source_ref"])
            if not ref.startswith("openapi.json#/"):
                raise ValueError(f"Expected a local schema reference, got {ref}")
            key = ref.removeprefix("openapi.json")
            if key in index:
                raise ValueError(f"Duplicate generated schema reference: {key}")
            index[key] = cast(str, model["class_name"])
        spec = json.loads(source.read_text())
        missing = {f"#/components/schemas/{name}" for name in spec["components"]["schemas"]} - index.keys()
        if missing:
            raise ValueError(f"Generator omitted component schemas: {sorted(missing)}")
        digest = hashlib.sha256(snapshot.read_bytes()).hexdigest()
        header = (
            "# Generated by scripts/generate_sdk_models.py; do not edit.\n"
            f"# datamodel-code-generator {VERSIONS['datamodel-code-generator']}; ruff {VERSIONS['ruff']}\n"
            f"# openapi/openapi.json SHA256: {digest}\n"
        )
        _ = output.write_text(header + output.read_text())
        # Match pre-commit's pinned Ruff without inheriting user/global config.
        for args in (["check", "--select", "E4,E7,E9,F,I", "--fix"], ["format", "--line-length", "120"]):
            _ = subprocess.run(
                [sys.executable, "-m", "ruff", *args, "--isolated", str(output)],
                check=True,
                capture_output=True,
            )
        return {
            "models.py": output.read_text(),
            "schema_index.json": json.dumps(index, indent=2, sort_keys=True) + "\n",
        }


def check_or_write(files: dict[str, str], destination: Path, *, check: bool) -> bool:
    """Return false for any missing/stale output, including files not tracked by git."""
    fresh = True
    for name, expected in files.items():
        path = destination / name
        actual = path.read_text() if path.exists() else ""
        if actual == expected:
            continue
        if check:
            fresh = False
            _ = sys.stderr.writelines(
                difflib.unified_diff(actual.splitlines(True), expected.splitlines(True), str(path), f"generated/{name}")
            )
        else:
            destination.mkdir(parents=True, exist_ok=True)
            _ = path.write_text(expected)
    return fresh


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    _ = parser.add_argument("--check", action="store_true", help="Fail on stale output without modifying files")
    args = parser.parse_args()
    files = render()
    if not check_or_write(files, OUTPUT, check=bool(args.check)):
        print("SDK models are stale. Run make sdk-codegen and commit both generated files.", file=sys.stderr)
        return 1
    print("SDK models are up to date." if args.check else "Generated SDK models and schema index.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
