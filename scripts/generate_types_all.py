#!/usr/bin/env python3
"""Generate the `__all__` export list of `notte_core.types`.

`notte_sdk.types` star-imports `notte_core.types`, so its `__all__` decides what the SDK exposes.
The list holds every public name the module defines (classes, functions, assignments) and every
name it re-exports with the explicit `from x import Name as Name` form. Plain imports (`os`,
`Path`, `BaseModel`, ...) are never exported. Run it after adding or removing a type:

    uv run --no-sync python scripts/generate_types_all.py           # rewrite the file
    uv run --no-sync python scripts/generate_types_all.py --check   # fail if out of date (pre-commit)
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

TYPES_MODULE = Path(__file__).resolve().parent.parent / "packages/notte-core/src/notte_core/types.py"
HEADER = (
    "# Generated by scripts/generate_types_all.py: public names defined here and `import X as X` re-exports.\n"
    "# A star import of this module must not re-export the modules and helpers it imports (os, json, Path, ...).\n"
)
BLOCK = re.compile(r"(?:^# .*\n)*^__all__ = \[\n(?:    \"\w+\",\n)*\]\n", re.M)


def exported_names(source: str) -> list[str]:
    names: set[str] = set()
    for node in ast.parse(source).body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names.update(target.id for target in node.targets if isinstance(target, ast.Name))
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            names.update(alias.asname for alias in node.names if alias.asname and alias.asname == alias.name)
        elif not isinstance(node, ast.Expr):
            # Names bound inside `if`/`try`/`with` blocks would be missed silently.
            raise ValueError(f"line {node.lineno}: unsupported top-level statement {type(node).__name__}")
    names.discard("__all__")
    return sorted(name for name in names if not name.startswith("_"))


def render(source: str) -> str:
    # Any other `__all__` assignment or mutation would override the generated list unchecked.
    outside = BLOCK.sub("", source, count=1)
    for node in ast.walk(ast.parse(outside)):
        if isinstance(node, ast.Name):
            bound = node.id
        elif isinstance(node, ast.alias):
            bound = node.asname or node.name
        elif isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            bound = node.name
        else:
            continue
        if bound == "__all__":
            raise ValueError(f"line {node.lineno}: __all__ is only set by the generated block")
    block = HEADER + "__all__ = [\n" + "".join(f'    "{name}",\n' for name in exported_names(source)) + "]\n"
    if BLOCK.search(source):
        return BLOCK.sub(lambda _: block, source, count=1)
    return source.rstrip("\n") + "\n\n\n" + block


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    _ = parser.add_argument("--check", action="store_true", help="fail instead of rewriting an out-of-date file")
    args = parser.parse_args()
    source = TYPES_MODULE.read_text()
    expected = render(source)
    if expected == source:
        return 0
    if args.check:
        print(f"{TYPES_MODULE} __all__ is out of date; run: uv run --no-sync python scripts/generate_types_all.py")
        return 1
    _ = TYPES_MODULE.write_text(expected)
    print(f"updated {TYPES_MODULE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
