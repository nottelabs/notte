#!/usr/bin/env python3
"""Generate the notte-sdk wire models from the committed OpenAPI snapshot.

The Notte API publishes its schema at ``<api>/openapi.json``. This script keeps a
snapshot of it in ``packages/notte-sdk/openapi/openapi.json`` and turns the
schemas the SDK uses into pydantic models and TypedDicts under
``notte_sdk/_generated``. The hand-written layer in ``notte_sdk/types.py``
subclasses those models and keeps the public names.

Usage::

    python scripts/generate_sdk_types.py              # regenerate from the snapshot
    python scripts/generate_sdk_types.py --check      # fail if generated files are stale (offline)
    python scripts/generate_sdk_types.py --fetch      # refresh the snapshot from staging, then regenerate
    python scripts/generate_sdk_types.py --fetch --url https://api.notte.cc

Generation runs datamodel-code-generator through ``uvx`` at a pinned version, then
formats the result with the ruff version pinned in ``.pre-commit-config.yaml``,
so the output is byte-for-byte reproducible and never rewritten by pre-commit.
Neither tool becomes a dependency of notte-sdk.
"""

from __future__ import annotations

import argparse
import copy
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Any, cast

REPO_ROOT = Path(__file__).resolve().parent.parent
SDK_ROOT = REPO_ROOT / "packages" / "notte-sdk"
SNAPSHOT = SDK_ROOT / "openapi" / "openapi.json"
GENERATED_DIR = SDK_ROOT / "src" / "notte_sdk" / "_generated"
MODELS_FILE = GENERATED_DIR / "models.py"
TYPEDDICTS_FILE = GENERATED_DIR / "typeddicts.py"

DEFAULT_URL = "https://us-staging.notte.cc"
DATAMODEL_CODEGEN = "datamodel-code-generator==0.83.0"

# Schemas the SDK builds on. Everything they reference is generated too. Grow this
# list as models move from hand-written to generated (see
# docs/design/openapi-generated-sdk-types.md).
RESPONSE_SCHEMAS = [
    "DeletePersonaResponse",
    "EmailResponse",
    "PersonaResponse",
    "SMSResponse",
    "SessionResponse",
]
REQUEST_SCHEMAS = [
    "ApiSessionStartRequest",
    "PersonaCreateRequest",
]

HEADER = (
    "# Generated by scripts/generate_sdk_types.py from packages/notte-sdk/openapi/openapi.json.\n"
    "# DO NOT EDIT. Run `make sdk-types` to regenerate.\n"
)

# Flags shared by the pydantic and TypedDict passes.
COMMON_FLAGS = [
    "--input-file-type",
    "openapi",
    "--target-python-version",
    "3.11",
    "--use-union-operator",
    "--use-standard-collections",
    "--enum-field-as-literal",
    "all",
    "--collapse-root-models",
    "--strict-nullable",
    "--use-double-quotes",
    "--disable-timestamp",
    "--keep-model-order",
    "--formatters",
    "builtin",
]
MODEL_FLAGS = [
    "--output-model-type",
    "pydantic_v2.BaseModel",
    "--use-annotated",
    "--field-constraints",
    "--use-schema-description",
    "--output-datetime-class",
    "datetime",
]
TYPEDDICT_FLAGS = [
    "--output-model-type",
    "typing.TypedDict",
    "--no-use-closed-typed-dict",
    # pydantic rejects typing.TypedDict on Python < 3.12; the SDK uses typing_extensions.
    "--import-overrides",
    json.dumps({"TypedDict": "typing_extensions", "NotRequired": "typing_extensions"}),
]


# ---------------------------------------------------------------------------
# Spec normalization
# ---------------------------------------------------------------------------

SCHEMA_LIST_KEYS = ("anyOf", "oneOf", "allOf", "prefixItems")
SCHEMA_KEYS = ("items", "additionalProperties", "not")

JsonObject = dict[str, Any]


def _object(node: Any) -> JsonObject | None:
    return cast(JsonObject, node) if isinstance(node, dict) else None


def _array(node: Any) -> list[Any]:
    return cast(list[Any], node) if isinstance(node, list) else []


def _refs(node: Any) -> set[str]:
    """Names of every component schema referenced anywhere under ``node``."""
    found: set[str] = set()
    obj = _object(node)
    if obj is not None:
        for key, value in obj.items():
            if key == "$ref" and isinstance(value, str):
                found.add(value.rsplit("/", 1)[-1])
            elif key == "mapping" and (mapping := _object(value)) is not None:
                found.update(str(target).rsplit("/", 1)[-1] for target in mapping.values())
            else:
                found |= _refs(value)
    for item in _array(node):
        found |= _refs(item)
    return found


def _closure(schemas: JsonObject, roots: list[str]) -> list[str]:
    missing = [name for name in roots if name not in schemas]
    if missing:
        raise SystemExit(f"Schemas not found in the OpenAPI snapshot: {missing}")
    seen: set[str] = set()
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        stack.extend(_refs(schemas[name]) - seen)
    return [name for name in schemas if name in seen]  # keep snapshot order


CONSTRAINT_KEYS = (
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "minLength",
    "maxLength",
    "pattern",
    "minItems",
    "maxItems",
)


def _hoist_nullable_constraints(schema: JsonObject) -> None:
    """Rewrite ``anyOf: [{primitive, constraints}, {null}]`` as a nullable primitive.

    Left nested, datamodel-codegen emits a ``RootModel`` per constrained branch
    (``viewport_width: ViewportWidth | None``), which callers would have to wrap
    their ints in. Rewritten as ``type: [integer, null]`` with the constraint
    beside it, it emits ``Annotated[int | None, Field(ge=500)]``; pydantic applies
    the constraint to the non-null branch.
    """
    branches = _array(schema.get("anyOf"))
    null: JsonObject = {"type": "null"}
    if len(branches) != 2 or null not in branches:
        return
    value = _object(next(branch for branch in branches if branch != null))
    if value is None or not isinstance(value.get("type"), str) or value["type"] == "object":
        return
    if not any(key in value for key in CONSTRAINT_KEYS) or set(value) - {"type", *CONSTRAINT_KEYS}:
        return
    del schema["anyOf"]
    schema.update(value)
    schema["type"] = [value["type"], "null"]


def _clean_schema(node: Any) -> None:
    """Drop noise that would leak into generated code.

    - ``title``: FastAPI derives one per property from its name; it adds nothing.
    - deprecated read-only properties: computed compatibility aliases on the server
      (e.g. ``SessionResponse.timeout_minutes``); the SDK layer re-adds them as
      deprecated properties instead of required fields.
    - constrained nullable primitives, see ``_hoist_nullable_constraints``.
    """
    schema = _object(node)
    if schema is None:
        return
    _ = schema.pop("title", None)
    _hoist_nullable_constraints(schema)
    properties = _object(schema.get("properties"))
    if properties is not None:
        dropped = [
            name
            for name, prop in properties.items()
            if (obj := _object(prop)) is not None and obj.get("readOnly") and obj.get("deprecated")
        ]
        for name in dropped:
            del properties[name]
        if dropped and "required" in schema:
            schema["required"] = [name for name in _array(schema["required"]) if name not in dropped]
        for prop in properties.values():
            _clean_schema(prop)
    for key in SCHEMA_LIST_KEYS:
        for sub in _array(schema.get(key)):
            _clean_schema(sub)
    for key in SCHEMA_KEYS:
        _clean_schema(schema.get(key))


def _subset(spec: JsonObject, roots: list[str]) -> JsonObject:
    schemas = cast(JsonObject, spec["components"]["schemas"])
    selected = {name: copy.deepcopy(schemas[name]) for name in _closure(schemas, roots)}
    for schema in selected.values():
        _clean_schema(schema)
    return {
        "openapi": spec["openapi"],
        "info": {"title": spec["info"]["title"], "version": "snapshot"},
        "paths": {},
        "components": {"schemas": selected},
    }


# ---------------------------------------------------------------------------
# Generation
# ---------------------------------------------------------------------------


def _ruff_version() -> str:
    config = (REPO_ROOT / ".pre-commit-config.yaml").read_text()
    match = re.search(r"astral-sh/ruff-pre-commit\s*\n\s*#[^\n]*\n\s*rev:\s*v?([\w.]+)", config) or re.search(
        r"astral-sh/ruff-pre-commit\s*\n\s*rev:\s*v?([\w.]+)", config
    )
    if match is None:
        raise SystemExit("Could not find the ruff-pre-commit rev in .pre-commit-config.yaml")
    return match.group(1)


def _run(cmd: list[str], *, stdin: str | None = None) -> str:
    result = subprocess.run(cmd, input=stdin, capture_output=True, text=True, cwd=REPO_ROOT, check=False)
    if result.returncode != 0:
        raise SystemExit(f"Command failed ({result.returncode}): {' '.join(cmd[:4])} ...\n{result.stderr}")
    return result.stdout


def _ruff(source: str, target: Path) -> str:
    """Format and lint-fix ``source`` exactly as the pre-commit ruff hooks would for ``target``."""
    ruff = ["uvx", f"ruff@{_ruff_version()}"]
    filename = str(target.relative_to(REPO_ROOT))
    fixed = _run([*ruff, "check", "--fix", "--quiet", "--exit-zero", "--stdin-filename", filename, "-"], stdin=source)
    return _run([*ruff, "format", "--quiet", "--stdin-filename", filename, "-"], stdin=fixed)


def _codegen(spec: JsonObject, flags: list[str], target: Path) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        spec_path = Path(tmp) / "openapi.json"
        out_path = Path(tmp) / "out.py"
        _ = spec_path.write_text(json.dumps(spec, indent=2))
        _ = _run(
            [
                "uvx",
                "--from",
                DATAMODEL_CODEGEN,
                "datamodel-codegen",
                "--input",
                str(spec_path),
                "--output",
                str(out_path),
                *COMMON_FLAGS,
                *flags,
            ]
        )
        source = out_path.read_text()
    # Replace datamodel-codegen's header (it embeds the temp file path).
    source = re.sub(r"\A(#[^\n]*\n)+", "", source).lstrip("\n")
    # basedpyright requires pydantic's model_config to be declared as a ClassVar.
    if "model_config = ConfigDict(" in source:
        source = source.replace("model_config = ConfigDict(", "model_config: ClassVar[ConfigDict] = ConfigDict(")
        source = source.replace("from typing import ", "from typing import ClassVar, ", 1)
    return _ruff(HEADER + "\n" + source, target)


def generate(spec: JsonObject) -> dict[Path, str]:
    models = _codegen(_subset(spec, RESPONSE_SCHEMAS + REQUEST_SCHEMAS), MODEL_FLAGS, MODELS_FILE)
    typeddicts = _codegen(_subset(spec, REQUEST_SCHEMAS), TYPEDDICT_FLAGS, TYPEDDICTS_FILE)
    return {MODELS_FILE: models, TYPEDDICTS_FILE: typeddicts}


def fetch(url: str) -> None:
    endpoint = f"{url.rstrip('/')}/openapi.json"
    print(f"Fetching {endpoint}")
    # The API's edge rejects urllib's default User-Agent.
    request = urllib.request.Request(
        endpoint, headers={"User-Agent": "notte-sdk-codegen", "Accept": "application/json"}
    )
    with urllib.request.urlopen(request, timeout=120) as response:  # noqa: S310 - https endpoint from --url
        spec = json.load(response)
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    _ = SNAPSHOT.write_text(json.dumps(spec, indent=2, ensure_ascii=False) + "\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    _ = parser.add_argument("--fetch", action="store_true", help="refresh the snapshot from the API first")
    _ = parser.add_argument("--url", default=DEFAULT_URL, help=f"API base URL for --fetch (default: {DEFAULT_URL})")
    _ = parser.add_argument("--check", action="store_true", help="fail if generated files differ from the snapshot")
    args = parser.parse_args()

    if args.fetch:
        fetch(args.url)

    spec = cast(JsonObject, json.loads(SNAPSHOT.read_text()))
    outputs = generate(spec)

    if args.check:
        stale = [path for path, content in outputs.items() if not path.exists() or path.read_text() != content]
        if stale:
            for path in stale:
                print(f"stale: {path.relative_to(REPO_ROOT)}", file=sys.stderr)
            print("Generated SDK types are out of date. Run `make sdk-types` and commit the result.", file=sys.stderr)
            return 1
        print("Generated SDK types are up to date with the OpenAPI snapshot.")
        return 0

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        _ = path.write_text(content)
        print(f"wrote {path.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
